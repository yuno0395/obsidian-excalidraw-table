export type MsgKey = keyof typeof en;
export function t(k: MsgKey): string {
  const lang = (moment.locale() || "en").toLowerCase();
  return (lang.startsWith("ja") ? ja : en)[k] ?? en[k];
}

const COLOR_JA: Record<string, string> = { Blue: "青", Teal: "青緑", Green: "緑", Yellow: "黄", Orange: "橙", Red: "赤", Violet: "紫", Gray: "灰" };
export function colorName(name: string): string {
  return (moment.locale() || "en").toLowerCase().startsWith("ja") ? COLOR_JA[name] ?? name : name;
}
